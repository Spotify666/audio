/** Minimal dependency-free RGBA PNG writer + a coverage-sampled canvas. */
import { deflateSync } from 'node:zlib'
import { writeFileSync } from 'node:fs'

const TABLE = (() => {
  const t = new Int32Array(256)
  for (let n = 0; n < 256; n++) {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    t[n] = c
  }
  return t
})()

const crc = (buf) => {
  let c = -1
  for (const b of buf) c = TABLE[(c ^ b) & 255] ^ (c >>> 8)
  return (c ^ -1) >>> 0
}

const chunk = (type, data) => {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const cc = Buffer.alloc(4)
  cc.writeUInt32BE(crc(body))
  return Buffer.concat([len, body, cc])
}

export function writePng(path, w, h, rgba) {
  const raw = Buffer.alloc((w * 4 + 1) * h)
  for (let y = 0; y < h; y++) {
    raw[y * (w * 4 + 1)] = 0
    rgba.copy(raw, y * (w * 4 + 1) + 1, y * w * 4, (y + 1) * w * 4)
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(w, 0)
  ihdr.writeUInt32BE(h, 4)
  ihdr[8] = 8
  ihdr[9] = 6
  writeFileSync(
    path,
    Buffer.concat([
      Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
      chunk('IHDR', ihdr),
      chunk('IDAT', deflateSync(raw, { level: 9 })),
      chunk('IEND', Buffer.alloc(0)),
    ]),
  )
}

export class Surface {
  constructor(w, h, bg) {
    this.w = w
    this.h = h
    this.buf = Buffer.alloc(w * h * 4)
    for (let i = 0; i < w * h; i++) {
      this.buf[i * 4] = bg[0]
      this.buf[i * 4 + 1] = bg[1]
      this.buf[i * 4 + 2] = bg[2]
      this.buf[i * 4 + 3] = 255
    }
  }
  blend(x, y, c, a) {
    if (a <= 0 || x < 0 || y < 0 || x >= this.w || y >= this.h) return
    const i = (y * this.w + x) * 4
    for (let k = 0; k < 3; k++) this.buf[i + k] = Math.round(this.buf[i + k] * (1 - a) + c[k] * a)
  }
  fill(x0, y0, x1, y1, c, inside, alpha = 1) {
    for (let y = Math.max(0, Math.floor(y0)); y < Math.min(this.h, Math.ceil(y1)); y++) {
      for (let x = Math.max(0, Math.floor(x0)); x < Math.min(this.w, Math.ceil(x1)); x++) {
        let hit = 0
        for (let sy = 0; sy < 3; sy++)
          for (let sx = 0; sx < 3; sx++)
            if (inside(x + (sx + 0.5) / 3, y + (sy + 0.5) / 3)) hit++
        if (hit) this.blend(x, y, c, (hit / 9) * alpha)
      }
    }
  }
  rect(x, y, w, h, c, a = 1) {
    this.fill(x, y, x + w, y + h, c, (px, py) => px >= x && px < x + w && py >= y && py < y + h, a)
  }
  roundBar(x, y, w, h, c, a = 1) {
    const r = Math.min(w, h) / 2
    this.fill(x, y, x + w, y + h, c, (px, py) => {
      const cx = Math.min(Math.max(px, x + r), x + w - r)
      const cy = Math.min(Math.max(py, y + r), y + h - r)
      return (px - cx) ** 2 + (py - cy) ** 2 <= r * r
    }, a)
  }
  ring(cx, cy, r, thickness, c, a = 1) {
    this.fill(cx - r - 1, cy - r - 1, cx + r + 1, cy + r + 1, c, (px, py) => {
      const d2 = (px - cx) ** 2 + (py - cy) ** 2
      return d2 <= r * r && d2 >= (r - thickness) ** 2
    }, a)
  }
  disc(cx, cy, r, c, a = 1) {
    this.fill(cx - r - 1, cy - r - 1, cx + r + 1, cy + r + 1, c, (px, py) =>
      (px - cx) ** 2 + (py - cy) ** 2 <= r * r, a)
  }
}

