export function text(surface, str, x, y, px, color, alpha = 1) {
  let cx = x
  for (const ch of str.toUpperCase()) {
    const glyph = FONT5x7[ch] ?? FONT5x7[' ']
    glyph.forEach((row, ry) => {
      ;[...row].forEach((cell, rx) => {
        if (cell === '#') surface.rect(cx + rx * px, y + ry * px, px, px, color, alpha)
      })
    })
    cx += px * 6
  }
  return cx - x - px
}
